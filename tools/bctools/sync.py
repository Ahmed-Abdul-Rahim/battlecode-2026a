"""Vendor the SDK-free crates into the submission bot.

cambc requires every bot's Cargo.toml to match its template, so a bot can't
depend on our crates by path, and a submitted bundle must be self-contained.
crates/* stays the canonical, host-tested source; this copies each crate's
src/ into bots/<bot>/src/<crate_name>/ (lib.rs -> mod.rs) and rewrites
`bc_core::` style paths to `crate::bc_core::`.

    python -m bctools.sync            # write
    python -m bctools.sync --check    # exit 1 if the vendored copy is stale (CI, pre-commit)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

try:
    from bctools import ROOT
except ImportError:  # run as a plain script (pre-commit hook without the project installed)
    ROOT = Path(__file__).resolve().parents[2]

CRATES = ["bc-core", "bc-path", "bc-brain", "bc-draft"]
MODULES = "bc_core|bc_path|bc_brain|bc_draft"
# `crate::x` inside a crate becomes `crate::<that crate>::x` once vendored.
INTRA_RE = re.compile(rf"(?<![\w$])crate::(?!(?:{MODULES})::)")
# Sibling crates `bc_x::` become `crate::bc_x::`.
PATH_RE = re.compile(rf"(?<![\w:])({MODULES})::")
HEADER = (
    "// @generated by tools/bctools/sync.py from crates/{crate}/src/{rel}. Edit the source, not this copy.\n"
)
MOD_ATTRS = "#![allow(dead_code, unused_imports)]\n"


def transform(text: str, crate: str, rel: str, is_root: bool) -> str:
    module = crate.replace("-", "_")
    body = INTRA_RE.sub(f"crate::{module}::", text)
    body = PATH_RE.sub(r"crate::\1::", body)
    head = HEADER.format(crate=crate, rel=rel)
    if is_root:
        head += MOD_ATTRS
    return head + body


def expected_files(bot: str) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for crate in CRATES:
        src = ROOT / "crates" / crate / "src"
        dest = ROOT / "bots" / bot / "src" / crate.replace("-", "_")
        for path in sorted(src.rglob("*.rs")):
            rel = path.relative_to(src).as_posix()
            target_rel = "mod.rs" if rel == "lib.rs" else rel
            text = path.read_text(encoding="utf-8")
            out[dest / target_rel] = transform(text, crate, rel, rel == "lib.rs")
    return out


def vendored_dirs(bot: str) -> list[Path]:
    return [ROOT / "bots" / bot / "src" / c.replace("-", "_") for c in CRATES]


def sync(bot: str = "main", check: bool = False) -> list[Path]:
    """Return the list of files that are (or were) out of date."""
    wanted = expected_files(bot)
    stale: list[Path] = []
    for path, text in wanted.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    for d in vendored_dirs(bot):
        if not d.exists():
            continue
        for path in d.rglob("*.rs"):
            if path not in wanted:
                stale.append(path)
                if not check:
                    path.unlink()
    return stale


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--bot", default="main")
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    stale = sync(args.bot, args.check)
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python -m bctools.sync)", file=sys.stderr)
        return 1 if stale else 0
    print(f"vendored {len(CRATES)} crates into bots/{args.bot}/src ({len(stale)} files updated)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
