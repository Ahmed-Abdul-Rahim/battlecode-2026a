"""Generate Rust and Python feature modules from schema.yaml.

Usage:
    python ml/features/gen.py          # write generated files
    python ml/features/gen.py --check  # exit 1 if generated files are stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))  # allow running as a script before `pip install -e .`

from ml.util import crc16  # noqa: E402

SCHEMA = ROOT / "ml" / "features" / "schema.yaml"
RUST_OUT = ROOT / "crates" / "bc-brain" / "src" / "features_gen.rs"
PY_OUT = ROOT / "ml" / "features" / "schema_gen.py"


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def load(path: Path = SCHEMA) -> dict:
    with path.open(encoding="utf-8") as f:
        schema = yaml.safe_load(f)
    groups = []
    names: list[str] = []
    feature_group: list[int] = []
    consts: list[tuple[str, int, int]] = []  # (CONST_NAME, start, length)
    for gi, group in enumerate(schema["groups"]):
        start = len(names)
        for feat in group["features"]:
            count = int(feat.get("count", 1))
            full = f"{group['name']}.{feat['name']}"
            consts.append((f"{group['name']}_{feat['name']}".upper(), len(names), count))
            for k in range(count):
                names.append(full if count == 1 else f"{full}[{k}]")
                feature_group.append(gi)
        groups.append(
            {
                "name": group["name"],
                "fuel": int(group["fuel"]),
                "start": start,
                "end": len(names),
                "source": group.get("source", ""),
            }
        )
    if len(set(names)) != len(names):
        raise ValueError("duplicate feature names in schema")
    return {
        "version": int(schema["version"]),
        "groups": groups,
        "names": names,
        "feature_group": feature_group,
        "consts": consts,
        "hash": crc16("\n".join(names).encode()),
    }


HEADER = "@generated by ml/features/gen.py from ml/features/schema.yaml. Do not edit."


def render_rust(s: dict) -> str:
    g = s["groups"]
    n = len(s["names"])
    lines = [
        f"// {HEADER}",
        "//! Feature indices, groups and per-group fuel costs.",
        "",
        f"pub const SCHEMA_VERSION: u32 = {s['version']};",
        f"pub const SCHEMA_HASH: u16 = {s['hash']:#06x};",
        f"pub const N_FEATURES: usize = {n};",
        f"pub const N_GROUPS: usize = {len(g)};",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "#[repr(u8)]",
        "pub enum Group {",
    ]
    lines += [f"    {camel(x['name'])} = {i}," for i, x in enumerate(g)]
    lines += [
        "}",
        "",
        "impl Group {",
        "    pub const ALL: [Self; N_GROUPS] = [",
    ]
    lines += [f"        Self::{camel(x['name'])}," for x in g]
    lines += [
        "    ];",
        "",
        "    #[must_use]",
        "    pub const fn name(self) -> &'static str {",
        "        match self {",
    ]
    lines += [f'            Self::{camel(x["name"])} => "{x["name"]}",' for x in g]
    lines += [
        "        }",
        "    }",
        "",
        "    /// Estimated per-turn fuel cost of extracting this group.",
        "    #[must_use]",
        "    pub const fn fuel(self) -> u32 {",
        "        match self {",
    ]
    lines += [f"            Self::{camel(x['name'])} => {x['fuel']}," for x in g]
    lines += [
        "        }",
        "    }",
        "",
        "    /// Feature index range `start..end`.",
        "    #[must_use]",
        "    pub const fn range(self) -> (usize, usize) {",
        "        match self {",
    ]
    lines += [f"            Self::{camel(x['name'])} => ({x['start']}, {x['end']})," for x in g]
    lines += [
        "        }",
        "    }",
        "}",
        "",
        "pub const FEATURE_NAMES: [&str; N_FEATURES] = [",
    ]
    lines += [f'    "{name}",' for name in s["names"]]
    lines += ["];", "", "/// Feature index constants. Vector features also get a `_LEN`.", "pub mod idx {"]
    for const, start, count in s["consts"]:
        lines.append(f"    pub const {const}: usize = {start};")
        if count > 1:
            lines.append(f"    pub const {const}_LEN: usize = {count};")
    lines += ["}", ""]
    return "\n".join(lines)


def render_python(s: dict) -> str:
    groups = ",\n".join(
        f"    {{'name': {x['name']!r}, 'fuel': {x['fuel']}, 'start': {x['start']}, 'end': {x['end']}}}"
        for x in s["groups"]
    )
    names = ",\n".join(f"    {name!r}" for name in s["names"])
    return (
        f'"""{HEADER}"""\n\n'
        f"SCHEMA_VERSION = {s['version']}\n"
        f"SCHEMA_HASH = {s['hash']:#06x}\n"
        f"N_FEATURES = {len(s['names'])}\n\n"
        f"GROUPS = [\n{groups},\n]\n\n"
        f"FEATURE_NAMES = [\n{names},\n]\n\n"
        f"FEATURE_GROUP = {s['feature_group']!r}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args(argv)
    s = load()
    outputs = {RUST_OUT: render_rust(s), PY_OUT: render_python(s)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python ml/features/gen.py)", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(s['names'])} features in {len(s['groups'])} groups, schema hash {s['hash']:#06x}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
